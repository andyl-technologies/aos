//! 9p submit, poll, and burst-done callback core.
//!
//! The 9p QEMU patch path treats virtio-9p as a raw-message pipe while Crucible
//! simulation mode is active. This module routes those raw 9p messages through
//! the reserved deterministic 9p executor rings and holds device-I/O virtual
//! time for the whole device invocation burst.

use std::{array, cell::Cell};

use thiserror::Error;

use crucible_shmem::{
    DirectedRing, FrameDeliveryKey, FrameEntry, FrameEntryError, NodeSlot, RingHeader, SLOT_9P_IO,
    SpscRingError,
};

use crate::{
    DeviceIoBurstState, DeviceIoFreezeError, DeviceIoRequestRelease, DeviceIoRequestToken,
    PluginDeviceIoFreeze, shmem_ordering::PluginShmemOrdering,
};

const NINEP_IO_SLOT_U32: u32 = SLOT_9P_IO as u32;
const MAX_NINEP_IN_FLIGHT_REQUESTS: usize = 256;
const NINEP_WIRE_HEADER_LEN: usize = 7;
const NINEP_RLERROR: u8 = 7;
const NINEP_NOTAG: u16 = u16::MAX;
const NINEP_EIO: u32 = 5;
const NINEP_EINVAL: u32 = 22;
const NINEP_ENOSYS: u32 = 38;
const NINEP_EROFS: u32 = 30;

/// Registration-time-fixed 9p callback state.
#[derive(Debug)]
pub struct PluginNinePIo {
    vm_slot: u32,
    ninep_slot: u32,
    outbound_ring_index: u32,
    inbound_ring_index: u32,
    next_request_id: Cell<u32>,
    pending_request_ids: PendingNinePRequests,
}

impl PluginNinePIo {
    /// Builds 9p callback state from the directed rings selected at registration.
    ///
    /// # Errors
    ///
    /// Returns [`NinePIoError::WrongOutboundRing`] or
    /// [`NinePIoError::WrongInboundRing`] when either ring is not the reserved
    /// 9p executor ring for `vm_slot`.
    pub fn from_directed_rings(
        vm_slot: u32,
        outbound_ring: DirectedRing,
        inbound_ring: DirectedRing,
    ) -> Result<Self, NinePIoError> {
        if outbound_ring.src_slot != vm_slot || outbound_ring.dst_slot != NINEP_IO_SLOT_U32 {
            return Err(NinePIoError::WrongOutboundRing {
                expected_src_slot: vm_slot,
                expected_dst_slot: NINEP_IO_SLOT_U32,
                expected_ring_index: None,
                actual_src_slot: outbound_ring.src_slot,
                actual_dst_slot: outbound_ring.dst_slot,
                actual_ring_index: outbound_ring.index,
            });
        }
        if inbound_ring.src_slot != NINEP_IO_SLOT_U32 || inbound_ring.dst_slot != vm_slot {
            return Err(NinePIoError::WrongInboundRing {
                expected_src_slot: NINEP_IO_SLOT_U32,
                expected_dst_slot: vm_slot,
                expected_ring_index: None,
                actual_src_slot: inbound_ring.src_slot,
                actual_dst_slot: inbound_ring.dst_slot,
                actual_ring_index: inbound_ring.index,
            });
        }

        Ok(Self::new(vm_slot, outbound_ring.index, inbound_ring.index))
    }

    /// Builds 9p callback state for the reserved 9p rings.
    #[must_use]
    pub fn new(vm_slot: u32, outbound_ring_index: u32, inbound_ring_index: u32) -> Self {
        Self {
            vm_slot,
            ninep_slot: NINEP_IO_SLOT_U32,
            outbound_ring_index,
            inbound_ring_index,
            next_request_id: Cell::new(0),
            pending_request_ids: PendingNinePRequests::new(),
        }
    }

    /// Returns the VM slot whose 9p device this state serves.
    #[must_use]
    pub const fn vm_slot(&self) -> u32 {
        self.vm_slot
    }

    /// Returns the reserved 9p executor slot.
    #[must_use]
    pub const fn ninep_slot(&self) -> u32 {
        self.ninep_slot
    }

    /// Returns the outbound 9p ring index.
    #[must_use]
    pub const fn outbound_ring_index(&self) -> u32 {
        self.outbound_ring_index
    }

    /// Returns the inbound 9p ring index.
    #[must_use]
    pub const fn inbound_ring_index(&self) -> u32 {
        self.inbound_ring_index
    }

    /// Returns the request id that the next successful submit will assign.
    #[must_use]
    pub fn next_request_id(&self) -> u32 {
        self.next_request_id.get()
    }

    /// Starts one multi-request 9p burst.
    ///
    /// # Errors
    ///
    /// Returns [`NinePIoError`] when the device-I/O freeze state rejects the
    /// burst transition.
    pub fn begin_burst(
        &self,
        freeze: &mut PluginDeviceIoFreeze,
        slot: &NodeSlot,
    ) -> Result<DeviceIoBurstState, NinePIoError> {
        freeze
            .begin_burst(slot)
            .map_err(|source| NinePIoError::DeviceIoFreeze { source })
    }

    /// Submits one raw 9p request message to the reserved 9p executor.
    ///
    /// Submit requires an active burst so the `device_io_active` hold spans every
    /// request generated by the same 9p device invocation.
    ///
    /// # Errors
    ///
    /// Returns [`NinePIoError`] when the ring does not match registration state,
    /// no burst is active, the request id overflows, frame construction fails,
    /// the freeze state rejects the request, or the outbound SPSC enqueue fails.
    pub fn submit_request(
        &self,
        freeze: &mut PluginDeviceIoFreeze,
        slot: &NodeSlot,
        outbound_ring: &mut NinePOutboundRing<'_>,
        submit_icount: u64,
        request: &NinePRequest,
    ) -> Result<NinePSubmit, NinePIoError> {
        self.check_outbound_ring(outbound_ring)?;
        if !freeze.burst_active() {
            return Err(NinePIoError::SubmitOutsideBurst);
        }

        let request_id = self.next_request_id.get();
        let next_request_id = request_id
            .checked_add(1)
            .ok_or(NinePIoError::RequestIdOverflow { request_id })?;
        let frame = FrameEntry::new(submit_icount, self.vm_slot, request_id, request.payload())
            .map_err(|source| NinePIoError::Frame { source })?;
        self.pending_request_ids.insert(request_id)?;
        let device_token = freeze.begin_submit(slot, submit_icount).map_err(|source| {
            let _ = self.pending_request_ids.remove(request_id);
            NinePIoError::DeviceIoFreeze { source }
        })?;

        if let Err(source) = PluginShmemOrdering::enqueue_outbound_frame(
            outbound_ring.header,
            outbound_ring.entries,
            &frame,
        ) {
            let release = freeze
                .fail_request(slot, device_token)
                .map_err(|source| NinePIoError::DeviceIoFreeze { source })?;
            self.pending_request_ids.remove(request_id)?;
            return Err(NinePIoError::RingEnqueueFailed {
                ring_index: self.outbound_ring_index,
                source,
                release,
            });
        }

        self.next_request_id.set(next_request_id);
        Ok(NinePSubmit {
            ring_index: self.outbound_ring_index,
            submit_icount,
            request_id,
            payload_len: request.payload().len(),
            token: NinePRequestToken {
                request_id,
                device_token,
            },
        })
    }

    /// Polls one raw 9p response and delivers it when its delivery icount is due.
    ///
    /// # Errors
    ///
    /// Returns [`NinePIoError`] when the inbound ring does not match registration
    /// state, the due response is malformed or for another request, the SPSC
    /// dequeue fails, delivery to QEMU fails, or the device-I/O token cannot be
    /// completed or failed.
    pub fn poll_response<D>(
        &self,
        freeze: &mut PluginDeviceIoFreeze,
        slot: &NodeSlot,
        inbound_ring: &NinePInboundRing<'_>,
        deliver: &mut D,
        current_icount: u64,
        token: NinePRequestToken,
    ) -> Result<NinePPoll, NinePIoError>
    where
        D: NinePGuestCompletion + ?Sized,
    {
        self.check_inbound_ring(inbound_ring)?;
        let Some(head) = peek_head_frame(inbound_ring)? else {
            return Ok(NinePPoll::NotReady { token });
        };
        if head.delivery_icount > current_icount {
            return Ok(NinePPoll::NotReady { token });
        }

        if head.src_node != self.ninep_slot {
            let release = self.fail_polled_request(freeze, slot, token)?;
            return Err(NinePIoError::UnexpectedSource {
                expected_src_node: self.ninep_slot,
                actual_src_node: head.src_node,
                frame: head.delivery_key(),
                release,
            });
        }
        if head.seq != token.request_id {
            if self.pending_request_ids.contains(head.seq) {
                return Ok(NinePPoll::NotReady { token });
            }
            let expected_request_id = token.request_id;
            let release = self.fail_polled_request(freeze, slot, token)?;
            return Err(NinePIoError::UnexpectedResponse {
                expected_request_id,
                actual_request_id: head.seq,
                frame: head.delivery_key(),
                release,
            });
        }

        let payload = match head.payload() {
            Ok(payload) => payload.to_vec(),
            Err(source) => {
                let release = self.fail_polled_request(freeze, slot, token)?;
                return Err(NinePIoError::MalformedResponse {
                    ring_index: self.inbound_ring_index,
                    frame: head.delivery_key(),
                    source,
                    release,
                });
            }
        };
        let response = NinePResponse::new(head.seq, payload);
        let request_id = token.request_id;
        let release = freeze
            .complete_request(slot, token.device_token)
            .map_err(|source| NinePIoError::DeviceIoFreeze { source })?;
        self.pending_request_ids.remove(request_id)?;

        let Some(dequeued) =
            PluginShmemOrdering::dequeue_inbound_frame(inbound_ring.header, inbound_ring.entries)
                .map_err(|source| NinePIoError::RingDequeue {
                ring_index: self.inbound_ring_index,
                source,
            })?
        else {
            return Err(NinePIoError::DequeuedUnexpectedFrame {
                ring_index: self.inbound_ring_index,
                expected: head.delivery_key(),
                actual: None,
            });
        };
        if dequeued.delivery_key() != head.delivery_key() {
            return Err(NinePIoError::DequeuedUnexpectedFrame {
                ring_index: self.inbound_ring_index,
                expected: head.delivery_key(),
                actual: Some(dequeued.delivery_key()),
            });
        }

        deliver.complete_9p_response(&response).map_err(|source| {
            NinePIoError::GuestCompletion {
                request_id: response.request_id(),
                release,
                source,
            }
        })?;
        Ok(NinePPoll::Completed { response, release })
    }

    /// Ends one 9p device burst after all request tokens have completed.
    ///
    /// # Errors
    ///
    /// Returns [`NinePIoError`] when no burst is active, a request is still
    /// pending, or the release wake fails.
    pub fn burst_done(
        &self,
        freeze: &mut PluginDeviceIoFreeze,
        slot: &NodeSlot,
    ) -> Result<DeviceIoBurstState, NinePIoError> {
        freeze
            .burst_done(slot)
            .map_err(|source| NinePIoError::DeviceIoFreeze { source })
    }

    fn fail_polled_request(
        &self,
        freeze: &mut PluginDeviceIoFreeze,
        slot: &NodeSlot,
        token: NinePRequestToken,
    ) -> Result<DeviceIoRequestRelease, NinePIoError> {
        let request_id = token.request_id;
        freeze
            .fail_request(slot, token.device_token)
            .map_err(|source| NinePIoError::DeviceIoFreeze { source })
            .and_then(|release| {
                self.pending_request_ids.remove(request_id)?;
                Ok(release)
            })
    }

    fn check_outbound_ring(&self, ring: &NinePOutboundRing<'_>) -> Result<(), NinePIoError> {
        if ring.ring_index != self.outbound_ring_index
            || ring.src_slot != self.vm_slot
            || ring.dst_slot != self.ninep_slot
        {
            Err(NinePIoError::WrongOutboundRing {
                expected_src_slot: self.vm_slot,
                expected_dst_slot: self.ninep_slot,
                expected_ring_index: Some(self.outbound_ring_index),
                actual_src_slot: ring.src_slot,
                actual_dst_slot: ring.dst_slot,
                actual_ring_index: ring.ring_index,
            })
        } else {
            Ok(())
        }
    }

    fn check_inbound_ring(&self, ring: &NinePInboundRing<'_>) -> Result<(), NinePIoError> {
        if ring.ring_index != self.inbound_ring_index
            || ring.src_slot != self.ninep_slot
            || ring.dst_slot != self.vm_slot
        {
            Err(NinePIoError::WrongInboundRing {
                expected_src_slot: self.ninep_slot,
                expected_dst_slot: self.vm_slot,
                expected_ring_index: Some(self.inbound_ring_index),
                actual_src_slot: ring.src_slot,
                actual_dst_slot: ring.dst_slot,
                actual_ring_index: ring.ring_index,
            })
        } else {
            Ok(())
        }
    }
}

/// A fixed-size pending request table for one 9p callback state.
#[derive(Debug)]
struct PendingNinePRequests {
    slots: [Cell<Option<u32>>; MAX_NINEP_IN_FLIGHT_REQUESTS],
}

impl PendingNinePRequests {
    fn new() -> Self {
        Self {
            slots: array::from_fn(|_| Cell::new(None)),
        }
    }

    fn insert(&self, request_id: u32) -> Result<(), NinePIoError> {
        let mut first_free = None;
        for (index, slot) in self.slots.iter().enumerate() {
            match slot.get() {
                Some(existing) if existing == request_id => {
                    return Err(NinePIoError::DuplicatePendingRequest { request_id });
                }
                None if first_free.is_none() => first_free = Some(index),
                _ => {}
            }
        }

        let Some(index) = first_free else {
            return Err(NinePIoError::PendingRequestCapacityExceeded {
                capacity: MAX_NINEP_IN_FLIGHT_REQUESTS,
            });
        };
        self.slots[index].set(Some(request_id));
        Ok(())
    }

    fn contains(&self, request_id: u32) -> bool {
        self.slots.iter().any(|slot| slot.get() == Some(request_id))
    }

    fn remove(&self, request_id: u32) -> Result<(), NinePIoError> {
        for slot in &self.slots {
            if slot.get() == Some(request_id) {
                slot.set(None);
                return Ok(());
            }
        }
        Err(NinePIoError::PendingRequestMissing { request_id })
    }
}

