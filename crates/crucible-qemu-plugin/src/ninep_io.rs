    #[derive(Default)]
    struct RecordingCompletion {
        responses: Vec<NinePResponse>,
        fail_message: Option<&'static str>,
    }

    impl NinePGuestCompletion for RecordingCompletion {
        fn complete_9p_response(
            &mut self,
            response: &NinePResponse,
        ) -> Result<(), NinePGuestCompletionError> {
            if let Some(message) = self.fail_message {
                return Err(NinePGuestCompletionError::new(message));
            }
            self.responses.push(response.clone());
            Ok(())
        }
    }

    fn layout() -> RegionLayout {
        match RegionLayout::for_config(RegionConfig::new(2, 4, 0)) {
            Ok(layout) => layout,
            Err(error) => panic!("layout should be valid: {error}"),
        }
    }

    fn ninep_rings(layout: RegionLayout, vm_slot: u32) -> (DirectedRing, DirectedRing) {
        let rings_per_vm = ReservedExecutorSlot::all().len() as u32 * 2;
        let index = vm_slot * rings_per_vm + 4;
        assert!(index + 1 < layout.ring_count);
        (
            DirectedRing {
                index,
                src_slot: vm_slot,
                dst_slot: NINEP_IO_SLOT_U32,
            },
            DirectedRing {
                index: index + 1,
                src_slot: NINEP_IO_SLOT_U32,
                dst_slot: vm_slot,
            },
        )
    }

    fn empty_entries(capacity: usize) -> Vec<FrameEntry> {
        vec![FrameEntry::default(); capacity]
    }

    fn outbound_ring<'a>(
        ring_index: u32,
        vm_slot: u32,
        header: &'a RingHeader,
        entries: &'a mut [FrameEntry],
    ) -> NinePOutboundRing<'a> {
        NinePOutboundRing::new(ring_index, vm_slot, NINEP_IO_SLOT_U32, header, entries)
    }

    fn inbound_ring<'a>(
        ring_index: u32,
        vm_slot: u32,
        header: &'a RingHeader,
        entries: &'a [FrameEntry],
    ) -> NinePInboundRing<'a> {
        NinePInboundRing::new(ring_index, NINEP_IO_SLOT_U32, vm_slot, header, entries)
    }

    fn start_burst(ninep: &PluginNinePIo, freeze: &mut PluginDeviceIoFreeze, slot: &NodeSlot) {
        if let Err(error) = handle_9p_burst_start_callback(ninep, freeze, slot) {
            panic!("9p burst should start: {error}");
        }
    }

    fn submit_raw(
        ninep: &PluginNinePIo,
        freeze: &mut PluginDeviceIoFreeze,
        slot: &NodeSlot,
        outbound: &mut NinePOutboundRing<'_>,
        submit_icount: u64,
    ) -> NinePSubmit {
        match ninep.submit_request(
            freeze,
            slot,
            outbound,
            submit_icount,
            &NinePRequest::new(b"Tread".to_vec()),
        ) {
            Ok(submit) => submit,
            Err(error) => panic!("9p submit should succeed: {error}"),
        }
    }

    fn response_frame(delivery_icount: u64, request_id: u32, payload: &[u8]) -> FrameEntry {
        frame(delivery_icount, NINEP_IO_SLOT_U32, request_id, payload)
    }

    fn frame(delivery_icount: u64, src_node: u32, seq: u32, payload: &[u8]) -> FrameEntry {
        match FrameEntry::new(delivery_icount, src_node, seq, payload) {
            Ok(frame) => frame,
            Err(error) => panic!("test frame should construct: {error}"),
        }
    }

    fn enqueue(header: &RingHeader, entries: &mut [FrameEntry], frame: FrameEntry) {
        if let Err(error) = PluginShmemOrdering::enqueue_outbound_frame(header, entries, &frame) {
            panic!("test frame should enqueue: {error}");
        }
    }

    fn assert_frame(frame: &FrameEntry, delivery_icount: u64, src_node: u32, seq: u32) {
        assert_eq!(frame.delivery_icount, delivery_icount);
        assert_eq!(frame.src_node, src_node);
        assert_eq!(frame.seq, seq);
        assert!(usize::from(frame.len) <= MAX_FRAME_DATA);
    }
