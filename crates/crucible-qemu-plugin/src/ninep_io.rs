/// A 9p wire-envelope decode or encode error.
#[derive(Clone, Debug, Error, PartialEq, Eq)]
pub enum NinePWireError {
    /// The frame is shorter than the fixed 9p header.
    #[error("9p frame length {len} is shorter than header")]
    ShortHeader {
        /// The observed frame length.
        len: usize,
    },
    /// The declared message size is smaller than the header.
    #[error("9p declared size {size} is smaller than header")]
    DeclaredSizeTooSmall {
        /// The declared size field.
        size: u32,
    },
    /// The declared message size exceeds the supplied frame bytes.
    #[error("9p declared size {size} exceeds available frame length {available}")]
    DeclaredSizeExceedsFrame {
        /// The declared size field.
        size: u32,
        /// The supplied frame length.
        available: usize,
    },
    /// The frame has bytes after the declared single message.
    #[error("9p declared size {size} leaves trailing bytes in frame length {frame_len}")]
    DeclaredSizeHasTrailingBytes {
        /// The declared size field.
        size: u32,
        /// The supplied frame length.
        frame_len: usize,
    },
    /// The declared message size exceeds the negotiated `msize`.
    #[error("9p declared size {size} exceeds negotiated msize {msize}")]
    DeclaredSizeExceedsMsize {
        /// The declared size field.
        size: u32,
        /// The negotiated maximum message size.
        msize: u32,
    },
    /// An encoded message length cannot fit in the wire size field.
    #[error("9p message length {len} cannot fit in u32")]
    MessageSizeOverflow {
        /// The unrepresentable message length.
        len: usize,
    },
}

fn ninep_lerror(tag: u16, errno: u32) -> NinePWireMessage {
    NinePWireMessage::new(NINEP_RLERROR, tag, errno.to_le_bytes().to_vec())
}

fn tag_from_header(frame: &[u8]) -> Option<u16> {
    if frame.len() < NINEP_WIRE_HEADER_LEN {
        return None;
    }
    Some(u16::from_le_bytes([frame[5], frame[6]]))
}

fn errno_for_valid_ninep_message(message_type: u8) -> u32 {
    match message_type {
        14 | 26 | 72 | 74 | 76 | 118 => NINEP_EROFS,
        8 | 12 | 22 | 24 | 30 | 40 | 100 | 104 | 108 | 110 | 116 | 120 => NINEP_EIO,
        _ => NINEP_ENOSYS,
    }
}

/// An error produced by 9p callback handling.
#[derive(Clone, Debug, Error, PartialEq, Eq)]
pub enum NinePIoError {
    /// The callback was handed a ring other than the fixed outbound 9p ring.
    #[error(
        "9p outbound ring mismatch: expected src={expected_src_slot} dst={expected_dst_slot} ring={expected_ring_index:?}, got src={actual_src_slot} dst={actual_dst_slot} ring={actual_ring_index}"
    )]
    WrongOutboundRing {
        /// The VM slot fixed at registration.
        expected_src_slot: u32,
        /// The 9p executor slot fixed at registration.
        expected_dst_slot: u32,
        /// The outbound ring index fixed at registration, if known.
        expected_ring_index: Option<u32>,
        /// The supplied ring's producer slot.
        actual_src_slot: u32,
        /// The supplied ring's consumer slot.
        actual_dst_slot: u32,
        /// The supplied ring's index.
        actual_ring_index: u32,
    },
    /// The callback was handed a ring other than the fixed inbound 9p ring.
    #[error(
        "9p inbound ring mismatch: expected src={expected_src_slot} dst={expected_dst_slot} ring={expected_ring_index:?}, got src={actual_src_slot} dst={actual_dst_slot} ring={actual_ring_index}"
    )]
    WrongInboundRing {
        /// The 9p executor slot fixed at registration.
        expected_src_slot: u32,
        /// The VM slot fixed at registration.
        expected_dst_slot: u32,
        /// The inbound ring index fixed at registration, if known.
        expected_ring_index: Option<u32>,
        /// The supplied ring's producer slot.
        actual_src_slot: u32,
        /// The supplied ring's consumer slot.
        actual_dst_slot: u32,
        /// The supplied ring's index.
        actual_ring_index: u32,
    },
    /// A 9p submit arrived without an active burst hold.
    #[error("9p submit arrived without an active burst")]
    SubmitOutsideBurst,
    /// The request id counter cannot represent another request.
    #[error("9p request id overflow at {request_id}")]
    RequestIdOverflow {
        /// The exhausted request id.
        request_id: u32,
    },
    /// The fixed pending-request table already contains this request id.
    #[error("9p request id {request_id} is already pending")]
    DuplicatePendingRequest {
        /// The duplicated request id.
        request_id: u32,
    },
    /// The fixed pending-request table has no free slot.
    #[error("9p pending request table is full at {capacity} requests")]
    PendingRequestCapacityExceeded {
        /// The fixed pending-request capacity.
        capacity: usize,
    },
    /// The fixed pending-request table was missing a request id being released.
    #[error("9p request id {request_id} was not pending")]
    PendingRequestMissing {
        /// The missing request id.
        request_id: u32,
    },
    /// Constructing a shared-memory frame failed.
    #[error("9p frame construction failed: {source}")]
    Frame {
        /// The frame construction error.
        source: FrameEntryError,
    },
    /// Device-I/O freeze state rejected a transition.
    #[error("9p device-I/O freeze failed: {source}")]
    DeviceIoFreeze {
        /// The device-I/O freeze error.
        source: DeviceIoFreezeError,
    },
    /// The outbound request enqueue failed after the freeze token was created.
    #[error("9p ring {ring_index} enqueue failed after freeze submit: {source}")]
    RingEnqueueFailed {
        /// The outbound ring index.
        ring_index: u32,
        /// The enqueue failure.
        source: SpscRingError,
        /// The release created by failing the just-created freeze token.
        release: DeviceIoRequestRelease,
    },
    /// The inbound ring operation failed.
    #[error("9p ring {ring_index} dequeue failed: {source}")]
    RingDequeue {
        /// The inbound ring index.
        ring_index: u32,
        /// The dequeue failure.
        source: SpscRingError,
    },
    /// The inbound ring head could not be decoded as a 9p response frame.
    #[error("9p ring {ring_index} malformed response at {frame:?}: {source}")]
    MalformedResponse {
        /// The inbound ring index.
        ring_index: u32,
        /// The frame key used to localize the malformed response.
        frame: FrameDeliveryKey,
        /// The frame payload error.
        source: FrameEntryError,
        /// The request release created by failing the pending token.
        release: DeviceIoRequestRelease,
    },
    /// The due response frame was not produced by the reserved 9p executor.
    #[error(
        "9p response source node {actual_src_node} does not match reserved 9p source {expected_src_node}"
    )]
    UnexpectedSource {
        /// The reserved 9p executor slot.
        expected_src_node: u32,
        /// The frame's advertised producer node.
        actual_src_node: u32,
        /// The response frame key.
        frame: FrameDeliveryKey,
        /// The request release created by failing the pending token.
        release: DeviceIoRequestRelease,
    },
    /// The due response did not match the request token being polled.
    #[error(
        "9p response request id {actual_request_id} does not match token {expected_request_id}"
    )]
    UnexpectedResponse {
        /// The token's request id.
        expected_request_id: u32,
        /// The response request id.
        actual_request_id: u32,
        /// The response frame key.
        frame: FrameDeliveryKey,
        /// The request release created by failing the pending token.
        release: DeviceIoRequestRelease,
    },
    /// The dequeued response did not match the previously peeked head.
    #[error("9p ring {ring_index} dequeued {actual:?} after peeking {expected:?}")]
    DequeuedUnexpectedFrame {
        /// The inbound ring index.
        ring_index: u32,
        /// The previewed frame key.
        expected: FrameDeliveryKey,
        /// The dequeued frame key, if any.
        actual: Option<FrameDeliveryKey>,
    },
    /// Delivering the raw response to the guest failed.
    #[error("9p request {request_id} guest completion failed: {source}")]
    GuestCompletion {
        /// The request id being completed.
        request_id: u32,
        /// The request release created before attempting guest completion.
        release: DeviceIoRequestRelease,
        /// The guest completion error.
        source: NinePGuestCompletionError,
    },
}

fn peek_head_frame(ring: &NinePInboundRing<'_>) -> Result<Option<FrameEntry>, NinePIoError> {
    let Some(delivery_icount) =
        PluginShmemOrdering::peek_inbound_delivery_icount(ring.header, ring.entries).map_err(
            |source| NinePIoError::RingDequeue {
                ring_index: ring.ring_index,
                source,
            },
        )?
    else {
        return Ok(None);
    };
    let slot = (PluginShmemOrdering::consumer_read_index(ring.header)
        & (ring.entries.len() as u64 - 1)) as usize;
    let frame = ring.entries[slot].clone();
    if frame.delivery_icount != delivery_icount {
        return Err(NinePIoError::DequeuedUnexpectedFrame {
            ring_index: ring.ring_index,
            expected: FrameDeliveryKey {
                delivery_icount,
                src_node: frame.src_node,
                seq: frame.seq,
            },
            actual: Some(frame.delivery_key()),
        });
    }
    Ok(Some(frame))
}

