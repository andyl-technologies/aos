    fn method_error_matrix_is_closed() {
        let session = session();
        let errors = [
            OwnershipProtocolErrorCodeV1::InvalidRequest,
            OwnershipProtocolErrorCodeV1::Unauthenticated,
            OwnershipProtocolErrorCodeV1::PermissionDenied,
            OwnershipProtocolErrorCodeV1::IncompatibleProtocol,
            OwnershipProtocolErrorCodeV1::RequiredCapabilityUnavailable,
            OwnershipProtocolErrorCodeV1::WrongAuthorityEpoch,
            OwnershipProtocolErrorCodeV1::IdempotencyConflict,
            OwnershipProtocolErrorCodeV1::AlreadyOwned,
            OwnershipProtocolErrorCodeV1::StaleExpectedPrior,
            OwnershipProtocolErrorCodeV1::NotFound,
            OwnershipProtocolErrorCodeV1::ResourceExhausted,
            OwnershipProtocolErrorCodeV1::DeadlineExceeded,
            OwnershipProtocolErrorCodeV1::Unavailable,
            OwnershipProtocolErrorCodeV1::IntegrityFailure,
            OwnershipProtocolErrorCodeV1::Internal,
        ];
        for method in methods() {
            for error in errors {
                let expected = match method {
                    OwnershipMethodV1::Begin => !matches!(
                        error,
                        OwnershipProtocolErrorCodeV1::StaleExpectedPrior
                            | OwnershipProtocolErrorCodeV1::NotFound
                    ),
                    OwnershipMethodV1::CompleteOrResume => {
                        !matches!(error, OwnershipProtocolErrorCodeV1::ResourceExhausted)
                    }
                    OwnershipMethodV1::Query => !matches!(
                        error,
                        OwnershipProtocolErrorCodeV1::AlreadyOwned
                            | OwnershipProtocolErrorCodeV1::StaleExpectedPrior
                            | OwnershipProtocolErrorCodeV1::NotFound
                            | OwnershipProtocolErrorCodeV1::ResourceExhausted
                    ),
                };
                assert_eq!(
                    session
                        .response(&request(method), OwnershipResponseOutcomeV1::Error(error))
                        .is_ok(),
                    expected,
                    "unexpected matrix result for {method:?}/{error:?}",
                );
            }
        }

        let acquired = claim();
        let renew = OwnershipClaimV1::renew(
            [11; 16],
            acquired.assignment(),
            DesiredGeneration::new(7),
            acquired.node(),
            crate::ExpectedOwnershipLease::new(6, ObjectDigest::from_bytes([12; 32]))
                .unwrap_or_else(|error| panic!("test fence failed: {error}")),
            60,
        )
        .unwrap_or_else(|error| panic!("test renewal failed: {error}"));
        let renew_request = session
            .request(OwnershipRequestBodyV1::Begin(Box::new(renew)))
            .unwrap_or_else(|error| panic!("test request failed: {error}"));
        assert!(
            session
                .response(
                    &renew_request,
                    OwnershipResponseOutcomeV1::Error(
                        OwnershipProtocolErrorCodeV1::StaleExpectedPrior
                    )
                )
                .is_ok()
        );
        assert_eq!(
            session.response(
                &renew_request,
                OwnershipResponseOutcomeV1::Error(OwnershipProtocolErrorCodeV1::AlreadyOwned)
            ),
            Err(OwnershipProtocolValidationError::InvalidResponseError),
        );
    }
