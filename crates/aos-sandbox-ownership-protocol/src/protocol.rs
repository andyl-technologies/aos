//! Bounded transport-neutral ownership transaction semantics.
//!
//! V1 has three methods: `Begin` durably admits an exact canonical claim,
//! `CompleteOrResume` explicitly drives or resumes issuance for that intent,
//! and `Query` observes only the exact request binding. A pending result may
//! include the crash window after external issuance but before local commit;
//! it therefore carries no evidence that issuance has not occurred. A
//! completed result returns exact canonical artifacts but does not establish
//! present lease liveness.
//!
//! This module deliberately does not choose a byte carrier. A local
//! `SOCK_SEQPACKET` adapter and a future authenticated remote adapter must both
//! validate into these types. Neither local credentials nor paths,
//! descriptors, monotonic deadlines, or backend journal details belong here.
//!
//! The session binding is SHA-256 over the domain string, selected version,
//! length-prefixed stable authority key ID, exact authority generation and
//! fingerprint, ownership-key usage code, canonical method codes, and the
//! three negotiated bounds, all integers big-endian. The all-zero hash alone
//! maps to the value one to reserve the zero sentinel. It correlates messages but does not replace
//! authentication by the eventual carrier. The client and server nonces must
//! be independently generated by a CSPRNG for every connection.

use aos_sandbox_core::model::{KeyReference, KeyUsage};
use aos_sandbox_core::{ObjectDigest, ProtocolId, ProtocolVersion, negotiate_protocol};
use sha2::{Digest as _, Sha256};

use crate::{
    MAXIMUM_REQUESTED_DURATION_SECONDS, OwnershipClaimV1, UnverifiedOwnershipLeaseResponse,
};

/// Maximum semantic request bytes a V1 carrier may admit.
pub const MAXIMUM_OWNERSHIP_REQUEST_BYTES: u32 = 4 * 1024;
/// Maximum semantic response bytes a V1 carrier may admit.
pub const MAXIMUM_OWNERSHIP_RESPONSE_BYTES: u32 = 256 * 1024;
/// Minimum response budget accepted during negotiation.
///
/// The ceiling always reserves both maximum canonical artifacts and bounded
/// envelope overhead, so a completed transaction can never become
/// unreturnable after it is durably admitted.
pub const MINIMUM_OWNERSHIP_RESPONSE_BYTES: u32 = 196 * 1024;
const MAXIMUM_METHODS: usize = 3;
const SESSION_BINDING_DOMAIN: &[u8] = b"aos-ownership-authority-session-v1\0";

/// Identifies one closed V1 ownership-authority method.
#[derive(Clone, Copy, Debug, Eq, Ord, PartialEq, PartialOrd)]
pub enum OwnershipMethodV1 {
    /// Durably admits an unsigned canonical ownership claim.
    Begin,
    /// Explicitly completes or resumes one previously admitted claim.
    CompleteOrResume,
    /// Queries one exact request-ID and claim-digest binding.
    Query,
}

impl OwnershipMethodV1 {
    const fn code(self) -> u8 {
        match self {
            Self::Begin => 1,
            Self::CompleteOrResume => 2,
            Self::Query => 3,
        }
    }
}

/// Binds follow-up operations and results to one immutable claim.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct OwnershipTransactionReferenceV1 {
    request_id: [u8; 16],
    claim_digest: ObjectDigest,
}

impl OwnershipTransactionReferenceV1 {
    /// Constructs a non-sentinel request and claim binding.
    ///
    /// # Errors
    ///
    /// Returns [`OwnershipProtocolValidationError::InvalidTransactionReference`]
    /// when either field is its all-zero sentinel.
    pub fn new(
        request_id: [u8; 16],
        claim_digest: ObjectDigest,
    ) -> Result<Self, OwnershipProtocolValidationError> {
        if request_id == [0; 16] || claim_digest.as_bytes() == &[0; 32] {
            return Err(OwnershipProtocolValidationError::InvalidTransactionReference);
        }
        Ok(Self {
            request_id,
            claim_digest,
        })
    }

    /// Derives the exact transaction binding from a validated canonical claim.
    #[must_use]
    pub fn from_claim(claim: &OwnershipClaimV1) -> Self {
        Self {
            request_id: *claim.request_id(),
            claim_digest: claim.digest(),
        }
    }

    /// Returns the stable idempotency request identity.
    #[must_use]
    pub const fn request_id(&self) -> &[u8; 16] {
        &self.request_id
    }

    /// Returns the domain-separated digest of the complete canonical claim.
    #[must_use]
    pub const fn claim_digest(&self) -> ObjectDigest {
        self.claim_digest
    }
}

/// Carries a method-specific request after hostile-input validation.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum OwnershipRequestBodyV1 {
    /// Carries the sole complete claim accepted from a client.
    Begin(Box<OwnershipClaimV1>),
    /// Names a durable intent without accepting replacement claim bytes.
    CompleteOrResume(OwnershipTransactionReferenceV1),
    /// Names the sole durable transaction that may be observed.
    Query(OwnershipTransactionReferenceV1),
}

impl OwnershipRequestBodyV1 {
    fn method(&self) -> OwnershipMethodV1 {
        match self {
            Self::Begin(_) => OwnershipMethodV1::Begin,
            Self::CompleteOrResume(_) => OwnershipMethodV1::CompleteOrResume,
            Self::Query(_) => OwnershipMethodV1::Query,
        }
    }

    fn transaction(&self) -> OwnershipTransactionReferenceV1 {
        match self {
            Self::Begin(claim) => OwnershipTransactionReferenceV1::from_claim(claim),
            Self::CompleteOrResume(reference) | Self::Query(reference) => *reference,
        }
    }
}

/// Owns an exact method/body/request binding independent of its carrier.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct OwnershipRequestEnvelopeV1 {
    session_binding: [u8; 32],
    method: OwnershipMethodV1,
    transaction: OwnershipTransactionReferenceV1,
    body: OwnershipRequestBodyV1,
}

impl OwnershipRequestEnvelopeV1 {
    /// Validates an independently decoded method tag and body.
    ///
    /// # Errors
    ///
    /// Returns [`OwnershipProtocolValidationError::MethodMismatch`] when the
    /// outer method tag does not exactly select the supplied body.
    fn from_parts(
        session_binding: [u8; 32],
        method: OwnershipMethodV1,
        body: OwnershipRequestBodyV1,
    ) -> Result<Self, OwnershipProtocolValidationError> {
        if method != body.method() {
            return Err(OwnershipProtocolValidationError::MethodMismatch);
        }
        Ok(Self {
            session_binding,
            method,
            transaction: body.transaction(),
            body,
        })
    }

    /// Returns the negotiated correlation transcript echoed by this request.
    #[must_use]
    pub const fn session_binding(&self) -> &[u8; 32] {
        &self.session_binding
    }

    /// Returns the closed method selected by this request.
    #[must_use]
    pub const fn method(&self) -> OwnershipMethodV1 {
        self.method
    }

    /// Returns the exact request-ID and claim-digest binding.
    #[must_use]
    pub const fn transaction(&self) -> OwnershipTransactionReferenceV1 {
        self.transaction
    }

    /// Returns the validated method-specific request.
    #[must_use]
    pub const fn body(&self) -> &OwnershipRequestBodyV1 {
        &self.body
    }
}

/// Describes durable transaction state without claiming live authority.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum OwnershipTransactionStatusV1 {
    /// No durable request binding existed at the query linearization point.
    Absent,
    /// An intent exists; external issuance may already have happened.
    Pending,
    /// Exact response artifacts were committed for the immutable request.
    Completed(UnverifiedOwnershipLeaseResponse),
}

/// Classifies portable protocol failures without backend diagnostics.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum OwnershipProtocolErrorCodeV1 {
    /// The message is malformed, non-canonical, or semantically invalid.
    InvalidRequest,
    /// The authenticated transport did not establish a caller identity.
    Unauthenticated,
    /// The established identity cannot perform the requested operation.
    PermissionDenied,
    /// No compatible ownership protocol version exists.
    IncompatibleProtocol,
    /// A mandatory semantic capability is unavailable.
    RequiredCapabilityUnavailable,
    /// The service's active authority key generation differs from the pin.
    WrongAuthorityEpoch,
    /// A request identity is already bound to different claim bytes.
    IdempotencyConflict,
    /// Expected absence failed because an owner already exists.
    AlreadyOwned,
    /// A renewal does not name the exact current lease fence.
    StaleExpectedPrior,
    /// Completion or query names no durable request binding.
    NotFound,
    /// The fixed authority epoch cannot admit another transaction.
    ResourceExhausted,
    /// The carrier deadline elapsed with an indeterminate transaction result.
    DeadlineExceeded,
    /// Linearizable authority state is temporarily unavailable.
    Unavailable,
    /// Protected state or a returned authority artifact failed authentication.
    IntegrityFailure,
    /// The implementation failed without safe backend detail.
    Internal,
}

/// Gives the normative recovery action for a stable error code.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum OwnershipErrorRecoveryV1 {
    /// Correct identity, configuration, or request bytes before another call.
    CorrectRequest,
    /// Observe the exact transaction, then retry only the identical operation.
    QueryThenRetryExact,
    /// Wait for an explicit authority-state or capacity transition.
    AwaitStateChange,
    /// Refresh authoritative state and create a newly planned request.
    RefreshAndReplan,
    /// Quarantine the service until protected integrity is restored.
    Quarantine,
}

impl OwnershipProtocolErrorCodeV1 {
    /// Returns the fixed recovery rule for this error class.
    #[must_use]
    pub const fn recovery(self) -> OwnershipErrorRecoveryV1 {
        match self {
            Self::DeadlineExceeded | Self::Unavailable | Self::Internal => {
                OwnershipErrorRecoveryV1::QueryThenRetryExact
            }
            Self::AlreadyOwned | Self::StaleExpectedPrior => {
                OwnershipErrorRecoveryV1::RefreshAndReplan
            }
            Self::ResourceExhausted => OwnershipErrorRecoveryV1::AwaitStateChange,
            Self::IntegrityFailure => OwnershipErrorRecoveryV1::Quarantine,
            Self::InvalidRequest
            | Self::Unauthenticated
            | Self::PermissionDenied
            | Self::IncompatibleProtocol
            | Self::RequiredCapabilityUnavailable
            | Self::WrongAuthorityEpoch
            | Self::IdempotencyConflict
            | Self::NotFound => OwnershipErrorRecoveryV1::CorrectRequest,
        }
    }
}

/// Carries either one bound transaction status or one stable error.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum OwnershipResponseOutcomeV1 {
    /// Reports a non-authorizing durable state observation.
    Status(OwnershipTransactionStatusV1),
    /// Reports a closed stable error code without backend-specific text.
    Error(OwnershipProtocolErrorCodeV1),
}

/// Binds every response to the exact request method and transaction identity.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct OwnershipResponseEnvelopeV1 {
    session_binding: [u8; 32],
    method: OwnershipMethodV1,
    transaction: OwnershipTransactionReferenceV1,
    outcome: OwnershipResponseOutcomeV1,
}

impl OwnershipResponseEnvelopeV1 {
    /// Validates a response under the V1 method/status state machine.
    ///
    /// `Absent` is query-only. Begin and completion may return only pending or
    /// completed status. Errors remain method-bound and carry no artifacts.
    ///
    /// # Errors
    ///
    /// Returns [`OwnershipProtocolValidationError::InvalidResponseStatus`]
    /// when a non-query response claims absence.
    fn new(
        session_binding: [u8; 32],
        method: OwnershipMethodV1,
        transaction: OwnershipTransactionReferenceV1,
        begin_action: Option<crate::OwnershipClaimAction>,
        outcome: OwnershipResponseOutcomeV1,
    ) -> Result<Self, OwnershipProtocolValidationError> {
        validate_outcome(method, begin_action, &outcome)?;
        Ok(Self {
            session_binding,
            method,
            transaction,
            outcome,
        })
    }

    /// Returns the negotiated correlation transcript echoed by this response.
    #[must_use]
    pub const fn session_binding(&self) -> &[u8; 32] {
        &self.session_binding
    }

    /// Returns the exact request method echoed by the response.
    #[must_use]
    pub const fn method(&self) -> OwnershipMethodV1 {
        self.method
    }

    /// Returns the exact request and claim binding echoed by the response.
    #[must_use]
    pub const fn transaction(&self) -> OwnershipTransactionReferenceV1 {
        self.transaction
    }

    /// Returns the stable response outcome.
    #[must_use]
    pub const fn outcome(&self) -> &OwnershipResponseOutcomeV1 {
        &self.outcome
    }
}

/// Checks that a response belongs to the exact originating request.
///
/// This check is mandatory even on an authenticated ordered carrier: it
/// prevents cross-method, cross-request, and cross-claim response substitution
/// by multiplexers and reconnect logic.
///
/// # Errors
///
/// Returns [`OwnershipProtocolValidationError::SessionBindingMismatch`] for a
/// request or response from another negotiation, and
/// [`OwnershipProtocolValidationError::ResponseBindingMismatch`] when the
/// method or immutable transaction reference differs.
pub fn validate_response_binding(
    session: &NegotiatedOwnershipSessionV1,
    request: &OwnershipRequestEnvelopeV1,
    response: &OwnershipResponseEnvelopeV1,
) -> Result<(), OwnershipProtocolValidationError> {
    if request.session_binding() != session.binding()
        || response.session_binding() != session.binding()
    {
        return Err(OwnershipProtocolValidationError::SessionBindingMismatch);
    }
    if request.method() != response.method() || request.transaction() != response.transaction() {
        return Err(OwnershipProtocolValidationError::ResponseBindingMismatch);
    }
    Ok(())
}

/// Carries the client's exact compatibility and authority-generation pin.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct OwnershipClientHelloV1 {
    client_nonce: [u8; 32],
    version: ProtocolVersion,
    expected_authority: KeyReference,
    required_methods: Vec<OwnershipMethodV1>,
    maximum_response_bytes: u32,
}

impl OwnershipClientHelloV1 {
    /// Constructs a bounded canonical client offer.
    ///
    /// Methods must be strictly ordered and unique. The authority reference
    /// must name a nonzero ownership-lease signing generation and fingerprint.
    /// The caller must generate `client_nonce` independently with a CSPRNG for
    /// this connection; this type can reject only the zero sentinel.
    ///
    /// # Errors
    ///
    /// Returns [`OwnershipProtocolValidationError`] for an incompatible
    /// version, zero nonce, invalid authority pin, non-canonical method set,
    /// or invalid response ceiling.
    pub fn new(
        client_nonce: [u8; 32],
        version: ProtocolVersion,
        expected_authority: KeyReference,
        required_methods: Vec<OwnershipMethodV1>,
        maximum_response_bytes: u32,
    ) -> Result<Self, OwnershipProtocolValidationError> {
        if client_nonce == [0; 32] {
            return Err(OwnershipProtocolValidationError::InvalidNonce);
        }
        negotiate_protocol(ProtocolId::OwnershipAuthority, version)
            .map_err(|_| OwnershipProtocolValidationError::IncompatibleProtocol)?;
        validate_authority(&expected_authority)?;
        validate_methods(&required_methods)?;
        if !(MINIMUM_OWNERSHIP_RESPONSE_BYTES..=MAXIMUM_OWNERSHIP_RESPONSE_BYTES)
            .contains(&maximum_response_bytes)
        {
            return Err(OwnershipProtocolValidationError::InvalidResponseBound);
        }
        Ok(Self {
            client_nonce,
            version,
            expected_authority,
            required_methods,
            maximum_response_bytes,
        })
    }

    /// Returns the client's per-connection CSPRNG nonce.
    #[must_use]
    pub const fn client_nonce(&self) -> &[u8; 32] {
        &self.client_nonce
    }

    /// Returns the exact offered semantic protocol version.
    #[must_use]
    pub const fn version(&self) -> ProtocolVersion {
        self.version
    }

    /// Returns the protected client configuration's authority-generation pin.
    #[must_use]
    pub const fn expected_authority(&self) -> &KeyReference {
        &self.expected_authority
    }

    /// Returns the canonical required method set.
    #[must_use]
    pub fn required_methods(&self) -> &[OwnershipMethodV1] {
        &self.required_methods
    }

    /// Returns the maximum complete response the client accepts.
    #[must_use]
    pub const fn maximum_response_bytes(&self) -> u32 {
        self.maximum_response_bytes
    }
}

/// Records one successfully negotiated V1 ownership session contract.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct NegotiatedOwnershipSessionV1 {
    version: ProtocolVersion,
    authority: KeyReference,
    methods: Vec<OwnershipMethodV1>,
    maximum_request_bytes: u32,
    maximum_response_bytes: u32,
    maximum_requested_lease_seconds: u64,
    binding: [u8; 32],
}

impl NegotiatedOwnershipSessionV1 {
    /// Negotiates an exact key epoch and closed method set.
    ///
    /// The authority key is never selected by fallback: it must exactly match
    /// the client's protected pin. Server methods must be strictly ordered and
    /// unique before subset validation. The server must generate
    /// `server_nonce` independently with a CSPRNG for this connection.
    ///
    /// # Errors
    ///
    /// Returns [`OwnershipProtocolValidationError`] for a zero server nonce,
    /// invalid server key, wrong authority epoch, non-canonical server methods,
    /// or a missing required method.
    pub fn negotiate(
        hello: &OwnershipClientHelloV1,
        server_nonce: [u8; 32],
        authority: KeyReference,
        methods: Vec<OwnershipMethodV1>,
    ) -> Result<Self, OwnershipProtocolValidationError> {
        if server_nonce == [0; 32] {
            return Err(OwnershipProtocolValidationError::InvalidNonce);
        }
        validate_authority(&authority)?;
        if authority != *hello.expected_authority() {
            return Err(OwnershipProtocolValidationError::WrongAuthorityEpoch);
        }
        validate_methods(&methods)?;
        if hello
            .required_methods()
            .iter()
            .any(|method| !methods.contains(method))
        {
            return Err(OwnershipProtocolValidationError::RequiredMethodUnavailable);
        }
        let maximum_request_bytes = MAXIMUM_OWNERSHIP_REQUEST_BYTES;
        let maximum_response_bytes = hello.maximum_response_bytes();
        let maximum_requested_lease_seconds = MAXIMUM_REQUESTED_DURATION_SECONDS;
        let binding = session_binding(
            hello,
            server_nonce,
            &authority,
            &methods,
            maximum_request_bytes,
            maximum_requested_lease_seconds,
        );
        Ok(Self {
            version: hello.version(),
            authority,
            methods,
            maximum_request_bytes,
            maximum_response_bytes,
            maximum_requested_lease_seconds,
            binding,
        })
    }

    /// Returns the exact selected semantic protocol version.
    #[must_use]
    pub const fn version(&self) -> ProtocolVersion {
        self.version
    }

    /// Returns the exact active ownership signing-key generation.
    #[must_use]
    pub const fn authority(&self) -> &KeyReference {
        &self.authority
    }

    /// Returns the closed supported method set.
    #[must_use]
    pub fn methods(&self) -> &[OwnershipMethodV1] {
        &self.methods
    }

    /// Returns the server's semantic request ceiling.
    #[must_use]
    pub const fn maximum_request_bytes(&self) -> u32 {
        self.maximum_request_bytes
    }

    /// Returns the selected complete response ceiling.
    #[must_use]
    pub const fn maximum_response_bytes(&self) -> u32 {
        self.maximum_response_bytes
    }

    /// Returns the largest duration any V1 claim may request.
    #[must_use]
    pub const fn maximum_requested_lease_seconds(&self) -> u64 {
        self.maximum_requested_lease_seconds
    }

    /// Returns the nonzero domain-separated negotiated correlation transcript.
    #[must_use]
    pub const fn binding(&self) -> &[u8; 32] {
        &self.binding
    }

    /// Constructs a request bound to this negotiated session.
    ///
    /// # Errors
    ///
    /// Returns [`OwnershipProtocolValidationError::MethodUnavailable`] when
    /// the body selects a method outside the negotiated set.
    pub fn request(
        &self,
        body: OwnershipRequestBodyV1,
    ) -> Result<OwnershipRequestEnvelopeV1, OwnershipProtocolValidationError> {
        let method = body.method();
        if !self.methods.contains(&method) {
            return Err(OwnershipProtocolValidationError::MethodUnavailable);
        }
        OwnershipRequestEnvelopeV1::from_parts(self.binding, method, body)
    }

    /// Validates independently decoded request fields against this session.
    ///
    /// # Errors
    ///
    /// Rejects a wrong transcript, unnegotiated method, or method/body mismatch.
    pub fn validate_request_parts(
        &self,
        binding: [u8; 32],
        method: OwnershipMethodV1,
        body: OwnershipRequestBodyV1,
    ) -> Result<OwnershipRequestEnvelopeV1, OwnershipProtocolValidationError> {
        if binding != self.binding || binding == [0; 32] {
            return Err(OwnershipProtocolValidationError::SessionBindingMismatch);
        }
        if !self.methods.contains(&method) {
            return Err(OwnershipProtocolValidationError::MethodUnavailable);
        }
        OwnershipRequestEnvelopeV1::from_parts(binding, method, body)
    }

    /// Constructs a trusted server-side response bound to this negotiated session.
    ///
    /// This builder derives metadata from `request`. Carrier decoders must use
    /// [`Self::validate_response_parts`] so hostile echoed fields are checked
    /// rather than normalized.
    ///
    /// # Errors
    ///
    /// Rejects an unnegotiated method or invalid method/outcome combination.
    pub fn response(
        &self,
        request: &OwnershipRequestEnvelopeV1,
        outcome: OwnershipResponseOutcomeV1,
    ) -> Result<OwnershipResponseEnvelopeV1, OwnershipProtocolValidationError> {
        if request.session_binding != self.binding {
            return Err(OwnershipProtocolValidationError::SessionBindingMismatch);
        }
        if !self.methods.contains(&request.method) {
            return Err(OwnershipProtocolValidationError::MethodUnavailable);
        }
        let begin_action = match request.body() {
            OwnershipRequestBodyV1::Begin(claim) => Some(claim.action()),
            OwnershipRequestBodyV1::CompleteOrResume(_) | OwnershipRequestBodyV1::Query(_) => None,
        };
        OwnershipResponseEnvelopeV1::new(
            self.binding,
            request.method,
            request.transaction,
            begin_action,
            outcome,
        )
    }

    /// Validates independently decoded response metadata before construction.
    ///
    /// This is the mandatory client-side carrier adapter boundary. It checks
    /// the exact transcript, negotiated method, echoed method and transaction,
    /// and the action-aware method/outcome matrix without replacing hostile
    /// values with locally derived ones.
    ///
    /// # Errors
    ///
    /// Returns [`OwnershipProtocolValidationError`] for a foreign transcript,
    /// unnegotiated or substituted method, substituted request ID or claim
    /// digest, or an invalid status/error combination.
    pub fn validate_response_parts(
        &self,
        request: &OwnershipRequestEnvelopeV1,
        binding: [u8; 32],
        method: OwnershipMethodV1,
        transaction: OwnershipTransactionReferenceV1,
        outcome: OwnershipResponseOutcomeV1,
    ) -> Result<OwnershipResponseEnvelopeV1, OwnershipProtocolValidationError> {
        if request.session_binding != self.binding || binding != self.binding || binding == [0; 32]
        {
            return Err(OwnershipProtocolValidationError::SessionBindingMismatch);
        }
        if !self.methods.contains(&method) {
            return Err(OwnershipProtocolValidationError::MethodUnavailable);
        }
        if method != request.method || transaction != request.transaction {
            return Err(OwnershipProtocolValidationError::ResponseBindingMismatch);
        }
        let begin_action = match request.body() {
            OwnershipRequestBodyV1::Begin(claim) => Some(claim.action()),
            OwnershipRequestBodyV1::CompleteOrResume(_) | OwnershipRequestBodyV1::Query(_) => None,
        };
        OwnershipResponseEnvelopeV1::new(binding, method, transaction, begin_action, outcome)
    }
}

/// Reports invalid hostile or independently decoded protocol semantics.
#[derive(Clone, Copy, Debug, Eq, PartialEq, thiserror::Error)]
pub enum OwnershipProtocolValidationError {
    /// The protocol major/minor offer is not supported.
    #[error("ownership authority protocol version is incompatible")]
    IncompatibleProtocol,
    /// The request ID or claim digest is an all-zero sentinel.
    #[error("ownership transaction reference is invalid")]
    InvalidTransactionReference,
    /// A client or server connection nonce is the all-zero sentinel.
    #[error("ownership authority connection nonce is invalid")]
    InvalidNonce,
    /// The outer method tag does not match the decoded body.
    #[error("ownership authority method does not match its body")]
    MethodMismatch,
    /// A non-query response claimed that the transaction is absent.
    #[error("ownership authority response status is invalid for its method")]
    InvalidResponseStatus,
    /// An error code is invalid for the selected method.
    #[error("ownership authority error is invalid for its method")]
    InvalidResponseError,
    /// A response method, request ID, or claim digest differs from its request.
    #[error("ownership authority response is not bound to its request")]
    ResponseBindingMismatch,
    /// A request or response does not echo the negotiated transcript.
    #[error("ownership authority session binding does not match")]
    SessionBindingMismatch,
    /// The selected method was not negotiated.
    #[error("ownership authority method was not negotiated")]
    MethodUnavailable,
    /// The authority key is not an exact usable ownership-lease generation.
    #[error("ownership authority key reference is invalid")]
    InvalidAuthority,
    /// The client pin and active authority key generation differ.
    #[error("ownership authority key generation does not match the client pin")]
    WrongAuthorityEpoch,
    /// A method list is empty, oversized, unsorted, or contains duplicates.
    #[error("ownership authority method set is not canonical")]
    InvalidMethodSet,
    /// The server does not implement one of the client's required methods.
    #[error("ownership authority required method is unavailable")]
    RequiredMethodUnavailable,
    /// The requested response budget is outside the fixed V1 range.
    #[error("ownership authority response bound is invalid")]
    InvalidResponseBound,
}

fn validate_authority(authority: &KeyReference) -> Result<(), OwnershipProtocolValidationError> {
    if authority.generation() == 0
        || authority.public_key_sha256().as_bytes() == &[0; 32]
        || authority.usage() != KeyUsage::OwnershipLease
    {
        return Err(OwnershipProtocolValidationError::InvalidAuthority);
    }
    Ok(())
}

fn validate_methods(methods: &[OwnershipMethodV1]) -> Result<(), OwnershipProtocolValidationError> {
    if methods.is_empty()
        || methods.len() > MAXIMUM_METHODS
        || methods.windows(2).any(|pair| pair[0] >= pair[1])
    {
        return Err(OwnershipProtocolValidationError::InvalidMethodSet);
    }
    Ok(())
}

fn validate_outcome(
    method: OwnershipMethodV1,
    begin_action: Option<crate::OwnershipClaimAction>,
    outcome: &OwnershipResponseOutcomeV1,
) -> Result<(), OwnershipProtocolValidationError> {
    match outcome {
        OwnershipResponseOutcomeV1::Status(status) => {
            let valid = match method {
                OwnershipMethodV1::Begin | OwnershipMethodV1::CompleteOrResume => {
                    !matches!(status, OwnershipTransactionStatusV1::Absent)
                }
                OwnershipMethodV1::Query => true,
            };
            if !valid {
                return Err(OwnershipProtocolValidationError::InvalidResponseStatus);
            }
        }
        OwnershipResponseOutcomeV1::Error(error) => {
            let common = matches!(
                error,
                OwnershipProtocolErrorCodeV1::InvalidRequest
                    | OwnershipProtocolErrorCodeV1::Unauthenticated
                    | OwnershipProtocolErrorCodeV1::PermissionDenied
                    | OwnershipProtocolErrorCodeV1::IncompatibleProtocol
                    | OwnershipProtocolErrorCodeV1::RequiredCapabilityUnavailable
                    | OwnershipProtocolErrorCodeV1::WrongAuthorityEpoch
                    | OwnershipProtocolErrorCodeV1::IdempotencyConflict
                    | OwnershipProtocolErrorCodeV1::DeadlineExceeded
                    | OwnershipProtocolErrorCodeV1::Unavailable
                    | OwnershipProtocolErrorCodeV1::IntegrityFailure
                    | OwnershipProtocolErrorCodeV1::Internal
            );
            let valid = common
                || match method {
                    OwnershipMethodV1::Begin => match begin_action {
                        Some(crate::OwnershipClaimAction::Acquire) => matches!(
                            error,
                            OwnershipProtocolErrorCodeV1::AlreadyOwned
                                | OwnershipProtocolErrorCodeV1::ResourceExhausted
                        ),
                        Some(crate::OwnershipClaimAction::Renew) => matches!(
                            error,
                            OwnershipProtocolErrorCodeV1::StaleExpectedPrior
                                | OwnershipProtocolErrorCodeV1::ResourceExhausted
                        ),
                        None => false,
                    },
                    OwnershipMethodV1::CompleteOrResume => matches!(
                        error,
                        OwnershipProtocolErrorCodeV1::AlreadyOwned
                            | OwnershipProtocolErrorCodeV1::StaleExpectedPrior
                            | OwnershipProtocolErrorCodeV1::NotFound
                    ),
                    OwnershipMethodV1::Query => false,
                };
            if !valid {
                return Err(OwnershipProtocolValidationError::InvalidResponseError);
            }
        }
    }
    Ok(())
}

fn session_binding(
    hello: &OwnershipClientHelloV1,
    server_nonce: [u8; 32],
    authority: &KeyReference,
    methods: &[OwnershipMethodV1],
    maximum_request_bytes: u32,
    maximum_requested_lease_seconds: u64,
) -> [u8; 32] {
    let mut digest = Sha256::new();
    digest.update(SESSION_BINDING_DOMAIN);
    digest.update(hello.client_nonce);
    digest.update(server_nonce);
    digest.update(hello.version.major().to_be_bytes());
    digest.update(hello.version.minor().to_be_bytes());
    let key_id = authority.stable_key_id().as_str().as_bytes();
    digest.update((key_id.len() as u16).to_be_bytes());
    digest.update(key_id);
    digest.update(authority.generation().to_be_bytes());
    digest.update(authority.public_key_sha256().as_bytes());
    digest.update([5]); // KeyUsage::OwnershipLease canonical trust-codec value.
    digest.update([methods.len() as u8]);
    for method in methods {
        digest.update([method.code()]);
    }
    digest.update(maximum_request_bytes.to_be_bytes());
    digest.update(hello.maximum_response_bytes.to_be_bytes());
    digest.update(maximum_requested_lease_seconds.to_be_bytes());
    let mut binding: [u8; 32] = digest.finalize().into();
    if binding == [0; 32] {
        binding[31] = 1;
    }
    binding
}

