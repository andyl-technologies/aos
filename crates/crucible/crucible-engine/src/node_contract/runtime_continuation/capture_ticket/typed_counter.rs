//! Names explicit typed views used by complete archive owning visitors.
//!
//! The closed roster covers Manifest, administrative journal, Host2/Host17,
//! Runtime7 and Scheduling1 field walks, including their existing terminal,
//! extension, input and lineage alternatives. Each concrete field type names its
//! borrowed generic-container views independently; no containing DTO's size is
//! used as a substitute for an iterator or child counter. Sequential visitor
//! branches are conservatively summed. Recursive/compiler frames are separate.

use super::{NodeRuntime, OwnedStorage, RuntimeError};
use std::mem::size_of;

// `OwnedStorage`'s Vec fold retains the iterator, slot count and accumulator;
// Option and Box dispatch retain borrowed views of their same concrete child.
// Requiring the actual trait keeps this roster tied to defining visitors.
fn typed_views<T: OwnedStorage + 'static>() -> usize {
    size_of::<&T>()
        + size_of::<&Vec<T>>()
        + size_of::<&Option<T>>()
        + size_of::<&Box<T>>()
        + size_of::<Option<&T>>()
        + size_of::<std::slice::Iter<'static, T>>()
        + size_of::<[usize; 2]>()
        + size_of::<Result<usize, RuntimeError>>()
}

