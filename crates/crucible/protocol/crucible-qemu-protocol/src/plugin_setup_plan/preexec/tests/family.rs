#[test]
fn literal_family_survives_current_encoder_with_both_execution_fields_zero() {
    let (plan, purpose) = issued_fixture_plan();
    let encoded = plan.encode_preexec(&purpose, None).unwrap();

    let purpose_start = encoded.len() - PURPOSE;
    assert_eq!(
        &encoded[purpose_start + 744..purpose_start + 1000],
        &FROZEN_FAMILY
    );
    assert_eq!(&FROZEN_FAMILY[112..120], &[0; 8]);
    assert_eq!(&FROZEN_FAMILY[208..216], &[0; 8]);
}

#[test]
fn family_refuses_changed_identity_header_role_and_reserved_fields() {
    let (plan, purpose) = issued_fixture_plan();
    for offset in [0, 8, 12, 16, 48, 64, 68, 112, 160, 164, 208] {
        let mut changed = purpose;
        changed[744 + offset] ^= 1;
        assert!(
            plan.encode_preexec(&changed, None).is_err(),
            "offset {offset}"
        );
    }
    for range in [56..64, 72..104, 168..200] {
        let mut changed = purpose;
        changed[744 + range.start..744 + range.end].fill(0);
        assert!(plan.encode_preexec(&changed, None).is_err());
    }
    let mut changed = purpose;
    changed[912..944].copy_from_slice(&purpose[816..848]);
    assert!(plan.encode_preexec(&changed, None).is_err());
}

#[test]
fn family_refuses_execution_numbers_and_overdrawn_local_limits() {
    let (plan, purpose) = issued_fixture_plan();
    for row in [64, 160] {
        for relative in [48, 56, 72, 80, 88] {
            let mut changed = purpose;
            changed[744 + row + relative..744 + row + relative + 8]
                .copy_from_slice(&u64::MAX.to_be_bytes());
            assert!(plan.encode_preexec(&changed, None).is_err());
        }
    }
    for offset in [40, 56, 64, 72, 80, 88] {
        let mut changed = purpose;
        changed[808 + offset] ^= 1;
        assert!(plan.encode_preexec(&changed, None).is_err());
    }
    for (relative, value) in [(40, 2049_u64), (56, 1025), (72, 65), (88, 2)] {
        let mut changed = purpose;
        changed[904 + relative..904 + relative + 8].copy_from_slice(&value.to_be_bytes());
        assert!(plan.encode_preexec(&changed, None).is_err());
    }
}

#[test]
fn old_carrier_purpose_and_target_role_cannot_supply_initial_source_reservations() {
    for (magic, schema, size) in [(b"CRUCPUR5", 5_u32, 744_usize), (b"CRUCPUR4", 4, 568)] {
        let mut bytes = selected();
        let start = bytes.len() - PURPOSE;
        bytes.truncate(start + size);
        bytes[start..start + 8].copy_from_slice(magic);
        bytes[start + 8..start + 12].copy_from_slice(&schema.to_be_bytes());
        bytes[start + 12..start + 16].copy_from_slice(&(size as u32).to_be_bytes());
        bytes[36..40].copy_from_slice(&(size as u32).to_be_bytes());
        let total = bytes.len() as u32;
        bytes[16..20].copy_from_slice(&total.to_be_bytes());
        assert!(decode_parts(&bytes).is_err());
    }
    let mut bytes = selected();
    bytes[..8].copy_from_slice(b"CRUCSUP5");
    bytes[8..12].copy_from_slice(&5_u32.to_be_bytes());
    assert!(decode_parts(&bytes).is_err());

    let (plan, mut purpose) = issued_fixture_plan();
    purpose[488..496].copy_from_slice(&1_u64.to_be_bytes());
    assert!(plan.encode_preexec(&purpose, None).is_err());
}
