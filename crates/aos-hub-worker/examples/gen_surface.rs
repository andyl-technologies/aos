//! Fixture generator: write a minimal, correctly signed registry surface.
//!
//! This example exists only to build the RFC-0004 worker integration test's
//! fixture hermetically. It writes a small **public** registry surface — the
//! exact R2 key layout the Worker's facade and Cron indexer consume — into a
//! directory, and prints the registry's pinned trust-anchor key line on stdout
//! so the test can seed it into D1's `registries.trust_keys`. It is a faithful,
//! trimmed copy of `aos_hub::seed::write_signed_surface`, reusing the
//! same wasm-clean `aos-registry-surface` primitives (`encode_loose`,
//! `encode_tree`, `sshsig::sign_armored`, `tag::render_tag_payload`) so the
//! generated bytes verify under the worker's own verifier.
//!
//! Usage (run by the fixture derivation):
//!
//! ```text
//! cargo run -p aos-hub-worker --example gen_surface -- <out-dir>
//! ```
//!
//! It prints two lines:
//!
//! ```text
//! TRUST_KEY <ssh-ed25519 ... maintainer>
//! HEAD_COMMIT <hex oid>
//! ```

use std::path::Path;

use anyhow::{Context, Result};
use ed25519_dalek::SigningKey;

use aos_registry_surface::object::{
    encode_loose, encode_tree, hash_object, ObjectKind, Oid, TreeEntry,
};
use aos_registry_surface::sshsig;
use aos_registry_surface::tag::render_tag_payload;

/// The release semver and channel the fixture publishes.
const SEMVER: &str = "1.0.0";
const CHANNEL: &str = "stable";
/// A deterministic timestamp for the signed objects (matches the hub seed).
const WHEN: i64 = 1_770_000_000;

fn main() -> Result<()> {
    let out = std::env::args()
        .nth(1)
        .context("usage: gen_surface <out-dir>")?;
    let root = Path::new(&out);
    std::fs::create_dir_all(root)?;

    // A fixed maintainer key — fine for a throwaway fixture, same as the hub
    // dev seed. The pinned trust line is printed for the test to store in D1.
    let key = SigningKey::from_bytes(&[7u8; 32]);
    let trust_key = sshsig::trusted_key_line("maintainer", &key.verifying_key());

    let head_commit = write_surface(root, &key, &trust_key)?;

    println!("TRUST_KEY {trust_key}");
    println!("HEAD_COMMIT {}", head_commit.to_hex());
    Ok(())
}

/// Write the full signed surface and return the HEAD commit oid.
fn write_surface(root: &Path, key: &SigningKey, trust_key: &str) -> Result<Oid> {
    let put_object = |kind: ObjectKind, content: &[u8]| -> Result<Oid> {
        let oid = hash_object(kind, content);
        let path = root.join(oid.loose_path());
        std::fs::create_dir_all(path.parent().context("loose path parent")?)?;
        std::fs::write(&path, encode_loose(kind, content)?)?;
        Ok(oid)
    };
    let put_blob = |s: &str| -> Result<Oid> { put_object(ObjectKind::Blob, s.as_bytes()) };
    let put_tree = |entries: &[(&str, &str, Oid)]| -> Result<Oid> {
        let entries: Vec<TreeEntry> = entries
            .iter()
            .map(|(mode, name, oid)| TreeEntry {
                mode: (*mode).to_string(),
                name: (*name).to_string(),
                oid: *oid,
            })
            .collect();
        put_object(ObjectKind::Tree, &encode_tree(&entries))
    };

    // Committed config: registry.toml + keys.toml + one package.
    let registry_toml = put_blob(
        "[registry]\nname = \"demo\"\ndescription = \"Demo registry (worker test fixture)\"\n",
    )?;
    let keys_toml = put_blob(&format!(
        "schema = 1\n\n[[keys]]\nid = \"maintainer\"\nkey = \"{trust_key}\"\n"
    ))?;
    let curl_toml = put_blob(
        "[package]\nname = \"curl\"\ndescription = \"Command-line URL transfers\"\n\
         license = \"MIT\"\nmaintainer = \"aos\"\n\n[[versions]]\nversion = \"8.5.0\"\n\n\
         [versions.platforms.x86_64-linux]\n\
         store_path = \"/var/lib/store/h7j3k8l2m9n4-curl-8.5.0\"\n\
         nar_hash = \"sha256:aa\"\nnar_size = 10\nclosure_size = 20\nreferences = []\n",
    )?;
    let c_bucket = put_tree(&[("100644", "curl.toml", curl_toml)])?;
    let packages = put_tree(&[("40000", "c", c_bucket)])?;

    let root_tree = put_tree(&[
        ("100644", "keys.toml", keys_toml),
        ("40000", "packages", packages),
        ("100644", "registry.toml", registry_toml),
    ])?;

    // Signed HEAD commit (gpgsig-sha256 armored header, the indexer's form).
    let commit = put_signed_commit(root, key, root_tree, &format!("release {SEMVER}"))?;

    // Signed release tag: a loose `tag` object whose payload targets the commit.
    let tag_body = render_tag_payload(SEMVER, &commit.to_hex(), "commit", "release", WHEN)?;
    let tag_armor = sshsig::sign_armored(tag_body.as_bytes(), key);
    let tag_content = format!("{tag_body}{tag_armor}\n");
    let tag_oid = put_object(ObjectKind::Tag, tag_content.as_bytes())?;

    // 256 signed channel partitions: each targets the release *tag object*.
    let part_body = render_tag_payload(CHANNEL, &tag_oid.to_hex(), "tag", "partition", WHEN)?;
    let part_armor = sshsig::sign_armored(part_body.as_bytes(), key);
    let partition = format!("{part_body}{part_armor}\n");
    let chan_dir = root.join("channels").join(CHANNEL);
    std::fs::create_dir_all(&chan_dir)?;
    for bucket in 0u16..=255 {
        std::fs::write(chan_dir.join(format!("{bucket:02x}")), partition.as_bytes())?;
    }

    // HEAD + info/refs (default branch = the channel; release tag advertised
    // with its peeled commit, as the indexer expects).
    std::fs::write(root.join("HEAD"), format!("ref: refs/heads/{CHANNEL}\n"))?;
    let mut refs = String::new();
    refs.push_str(&format!("{}\trefs/heads/{CHANNEL}\n", commit.to_hex()));
    refs.push_str(&format!("{}\trefs/tags/{SEMVER}\n", tag_oid.to_hex()));
    refs.push_str(&format!("{}\trefs/tags/{SEMVER}^{{}}\n", commit.to_hex()));
    std::fs::create_dir_all(root.join("info"))?;
    std::fs::write(root.join("info/refs"), refs)?;

    // Static nix-cache surface: nix-cache-info + one narinfo + one NAR.
    std::fs::write(
        root.join("nix-cache-info"),
        "StoreDir: /var/lib/store\nPriority: 40\n",
    )?;
    std::fs::write(
        root.join("h7j3k8l2m9n4.narinfo"),
        "StorePath: /var/lib/store/h7j3k8l2m9n4-curl-8.5.0\nURL: nar/h7j3k8l2m9n4.nar.zst\n\
         Compression: zstd\nNarHash: sha256:aa\nNarSize: 10\nReferences: \n",
    )?;
    std::fs::create_dir_all(root.join("nar"))?;
    std::fs::write(root.join("nar/h7j3k8l2m9n4.nar.zst"), b"not-a-real-nar")?;

    Ok(commit)
}

/// Write a maintainer-signed commit (gpgsig-sha256 armored header) over `tree`.
fn put_signed_commit(root: &Path, key: &SigningKey, tree: Oid, message: &str) -> Result<Oid> {
    let ident = format!("AOS Fixture <fixture@aos> {WHEN} +0000");
    let unsigned = format!(
        "tree {tree}\nauthor {ident}\ncommitter {ident}\n\n{message}\n",
        tree = tree.to_hex(),
    );
    let armor = sshsig::sign_armored(unsigned.as_bytes(), key);
    let mut lines = armor.lines();
    let first = lines.next().context("armor has a first line")?;
    let mut gpgsig = format!("gpgsig-sha256 {first}\n");
    for line in lines {
        gpgsig.push(' ');
        gpgsig.push_str(line);
        gpgsig.push('\n');
    }
    let signed = format!(
        "tree {tree}\nauthor {ident}\ncommitter {ident}\n{gpgsig}\n{message}\n",
        tree = tree.to_hex(),
    );
    let oid = hash_object(ObjectKind::Commit, signed.as_bytes());
    let path = root.join(oid.loose_path());
    std::fs::create_dir_all(path.parent().context("commit loose path parent")?)?;
    std::fs::write(&path, encode_loose(ObjectKind::Commit, signed.as_bytes())?)?;
    Ok(oid)
}
