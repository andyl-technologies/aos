/// The exact `/run/systemd/system` surface a [`CompilePlan`] maps to.
///
/// Produced by [`GraphCompiler::render`] without touching disk, so the format
/// contract is unit-testable. Paths are absolute under the compiler's run root.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PlannedArtifacts {
    /// `dropin path → file contents`.
    pub dropins: BTreeMap<PathBuf, String>,
    /// `symlink path → link target`.
    pub symlinks: BTreeMap<PathBuf, PathBuf>,
}

/// Render the verbatim `10-edges.conf` body for `pkg` and its `deps`.
///
/// Always emits the `After=aos-pkg-fetch@<pkg>.service` self-edge; emits the
/// `After=`/`Wants=` config-edge lines only when `deps` is non-empty (an empty
/// `[Unit]` section is never produced — build-spec §2.1). `deps` is a sorted set
/// so the output is deterministic.
fn dropin_contents(pkg: &str, deps: &BTreeSet<String>) -> String {
    let mut out = String::new();
    out.push_str("# Generated by aos-graph-compile from /run/aos/{manifest,graph}.json.\n");
    out.push_str("# Do not edit; regenerated on every `apm switch`/`upgrade`.\n");
    out.push_str("[Unit]\n");
    out.push_str(&format!("After=aos-pkg-fetch@{pkg}.service\n"));
    if !deps.is_empty() {
        let instances: Vec<String> = deps
            .iter()
            .map(|d| format!("aos-pkg-install@{d}.service"))
            .collect();
        let joined = instances.join(" ");
        out.push_str(&format!("After={joined}\n"));
        out.push_str(&format!("Wants={joined}\n"));
    }
    out
}

