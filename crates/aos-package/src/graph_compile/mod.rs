//! The systemd unit-graph compiler for configuration manifests.
//!
//! `aos-eval.service` produces two read-only inputs — `/run/aos/manifest.json`
//! (the resolved package set + config) and `/run/aos/graph.json` (the
//! cross-package read/write DAG) — and never activates. This module is the
//! `aos-graph-compile.service` body that turns those inputs into a runtime
//! systemd graph so that systemd's own ordering, parallelism, and failure
//! isolation drive provisioning, rather than a monolithic `apm install`.
//!
//! # What it writes
//!
//! Everything heavyweight (the `aos-pkg-fetch@.service` / `aos-pkg-install@.service`
//! template bodies, sandboxing, the three targets) is image-baked into gen-0
//! (`modules/systemd/graph.nix`). At runtime the compiler writes only a small,
//! deterministic surface under `/run/systemd/system/` (tmpfs, outranks `/etc`
//! and `/usr`, outside the composefs `/etc` overlay — invariant **I1**):
//!
//! - one per-instance dropin per package, `aos-pkg-install@<p>.service.d/10-edges.conf`,
//!   mirroring the config DAG;
//! - `.wants/` symlinks pulling each instance from its target;
//!
//! then it calls `daemon-reload` once and `start --no-block aos-config.target`
//! through the [`SystemdControl`] seam (invariant **I2** — the compiler drives
//! systemd through nothing else). The on-disk surface is a pure function of the
//! two inputs (invariant **I3**): re-running over identical inputs is a
//! byte-identical no-op.
//!
//! # The dropin format
//!
//! ```ini
//! # Generated by aos-graph-compile from /run/aos/{manifest,graph}.json.
//! # Do not edit; regenerated on every `apm switch`/`upgrade`.
//! [Unit]
//! After=aos-pkg-fetch@nginx.service
//! After=aos-pkg-install@firewall.service
//! Wants=aos-pkg-install@firewall.service
//! ```
//!
//! The fetch self-edge is `After=` only (an unmet fetch leaves render *inactive*,
//! not failed — the package degrades); config edges are `After=`+`Wants=` (soft,
//! so a dependency's failure isolates). The compiler emits **no**
//! `Requires=`/`BindsTo=`/`Requisite=` anywhere — that is the lever that turns a
//! one-bad-package failure into degraded-not-failed boot (build-spec §3).
//!
//! # Module map
//!
//! - [`reproject`] — the degraded re-projected-manifest commit (build-spec §5):
//!   restrict the full manifest to the packages that materialized, close under
//!   the config graph, re-hash into a content-addressed generation, record the
//!   drop-set.
//! - [`subverbs`] — the `apm fetch <pkg>` / `apm render-one <pkg>` handlers that
//!   back the template `ExecStart=`s (build-spec §4).

