/// Run the compiler as `aos-graph-compile.service`: read the two inputs, open a
/// real [`aos_systemd::SystemdClient`], and drive the compile.
///
/// `ConditionPathExists=/run/aos/manifest.json` on the unit guarantees the
/// manifest is present before this runs; a missing graph.json is treated as an
/// empty graph (independent packages, no ordering).
///
/// # Errors
///
/// Returns an error if the manifest cannot be read or parsed, if the plan is
/// invalid (bad name, cycle), or if any systemd call fails. The service then
/// exits non-zero and the box stays on the gen-0 seed.
pub async fn run_graph_compile_command(
    manifest_path: &Path,
    graph_path: &Path,
    run_root: Option<&Path>,
) -> Result<()> {
    let manifest_text = std::fs::read_to_string(manifest_path)
        .with_context(|| format!("reading manifest {}", manifest_path.display()))?;
    let manifest: Value = serde_json::from_str(&manifest_text)
        .with_context(|| format!("parsing manifest {}", manifest_path.display()))?;

    let graph = if graph_path.exists() {
        let graph_text = std::fs::read_to_string(graph_path)
            .with_context(|| format!("reading graph {}", graph_path.display()))?;
        ConfigGraph::from_json(&graph_text)?
    } else {
        ConfigGraph::default()
    };

    let compiler = match run_root {
        Some(root) => GraphCompiler::with_run_root(root),
        None => GraphCompiler::new(),
    };

    let client = aos_systemd::SystemdClient::connect()
        .await
        .context("connecting to systemd")?;
    let report = compiler.compile(&manifest, &graph, &client).await?;
    eprintln!(
        "aos-graph-compile: {} package instance(s) wired, {} removed; started {CONFIG_TARGET}",
        report.written.len(),
        report.removed.len(),
    );
    Ok(())
}
