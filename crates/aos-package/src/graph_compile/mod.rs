/// The validated, cycle-free package graph the compiler renders to disk.
///
/// Built by [`plan`] from the manifest's package set intersected with the graph
/// edges. Package names are validated against the apm `packageNameRegex` so they
/// are safe to interpolate into systemd instance names and `/run` paths.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CompilePlan {
    /// Every package that gets a fetch + install instance, sorted.
    packages: BTreeSet<String>,
    /// `package → its install-ordering dependencies` (config out-neighbors that
    /// are themselves in `packages`), each set sorted for determinism.
    edges: BTreeMap<String, BTreeSet<String>>,
}

impl CompilePlan {
    /// The packages this plan materializes instances for.
    pub fn packages(&self) -> &BTreeSet<String> {
        &self.packages
    }

    /// The install-ordering dependencies of `pkg` (may be empty).
    pub fn dependencies(&self, pkg: &str) -> BTreeSet<String> {
        self.edges.get(pkg).cloned().unwrap_or_default()
    }
}

/// Build a [`CompilePlan`] from the eval outputs.
///
/// The package set is read from `manifest.packages` when present (the resolved
/// working set); otherwise it falls back to the union of the graph's nodes, so
/// the compiler is robust to either manifest shape. Edges are restricted to
/// endpoints in the package set, every name is validated, and the graph is
/// checked for cycles (defensively — a non-converging eval fails `aos-eval`
/// before any graph exists, build-spec §3).
///
/// # Errors
///
/// Returns an error if a package name is invalid, if an edge names a package
/// outside the manifest set, or if the graph contains a cycle (with the cycle
/// path in the message).
pub fn plan(manifest: &Value, graph: &ConfigGraph) -> Result<CompilePlan> {
    let packages = read_packages(manifest, graph);
    for pkg in &packages {
        validate_package_name(pkg)
            .with_context(|| format!("manifest package '{pkg}' is not a valid apm package name"))?;
    }

    let mut edges: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for pkg in &packages {
        let mut deps = BTreeSet::new();
        for dep in graph.deps_of(pkg) {
            validate_package_name(dep)
                .with_context(|| format!("graph dependency '{dep}' is not a valid package name"))?;
            if dep == pkg {
                // A self-loop in graph.json is meaningless (a package does not
                // order against itself); drop it rather than emit a systemd
                // ordering cycle.
                continue;
            }
            if !packages.contains(dep) {
                bail!(
                    "graph.json edge '{pkg}' -> '{dep}' names a package not in the manifest set"
                );
            }
            deps.insert(dep.clone());
        }
        edges.insert(pkg.clone(), deps);
    }

    detect_cycle(&edges)?;

    Ok(CompilePlan { packages, edges })
}

/// Read the package set: `manifest.packages` if present, else the graph nodes.
fn read_packages(manifest: &Value, graph: &ConfigGraph) -> BTreeSet<String> {
    if let Some(names) = manifest.get("packages").and_then(package_names) {
        return names;
    }
    // Fallback: every node mentioned by the graph (keys and out-neighbors).
    let mut set = BTreeSet::new();
    for (pkg, deps) in &graph.edges {
        set.insert(pkg.clone());
        set.extend(deps.iter().cloned());
    }
    set
}

/// Extract package names from a `manifest.packages` value, accepting either a
/// `["nginx", …]` array of strings or a `[{ "name": "nginx" }, …]` array of
/// objects (with `name` or `package` keys).
fn package_names(v: &Value) -> Option<BTreeSet<String>> {
    let arr = v.as_array()?;
    let mut set = BTreeSet::new();
    for item in arr {
        if let Some(s) = item.as_str() {
            set.insert(s.to_string());
        } else if let Some(obj) = item.as_object() {
            let name = obj
                .get("name")
                .or_else(|| obj.get("package"))
                .and_then(Value::as_str)?;
            set.insert(name.to_string());
        } else {
            return None;
        }
    }
    Some(set)
}

/// Detect an ordering cycle via DFS, reporting the offending path.
///
/// # Errors
///
/// Returns an error naming the cycle (e.g. `a -> b -> a`) when one is found.
fn detect_cycle(edges: &BTreeMap<String, BTreeSet<String>>) -> Result<()> {
    /// DFS coloring: `White` unvisited, `Gray` on the active stack, `Black` done.
    #[derive(Clone, Copy, PartialEq, Eq)]
    enum Color {
        Gray,
        Black,
    }

    let mut color: BTreeMap<&str, Color> = BTreeMap::new();
    // Iterative DFS so a pathological graph cannot blow the stack. Each stack
    // frame carries the node and the index of the next neighbor to visit.
    for root in edges.keys() {
        if color.contains_key(root.as_str()) {
            continue;
        }
        let mut stack: Vec<(&str, std::collections::btree_set::Iter<'_, String>)> =
            vec![(root.as_str(), edges[root].iter())];
        color.insert(root.as_str(), Color::Gray);
        while let Some((node, iter)) = stack.last_mut() {
            let node = *node;
            match iter.next() {
                Some(next) => match color.get(next.as_str()) {
                    Some(Color::Gray) => {
                        // Back-edge: reconstruct the cycle from the active stack.
                        let mut path: Vec<&str> =
                            stack.iter().map(|(n, _)| *n).collect();
                        if let Some(pos) = path.iter().position(|n| *n == next.as_str()) {
                            path = path[pos..].to_vec();
                        }
                        path.push(next.as_str());
                        bail!("graph.json contains an ordering cycle: {}", path.join(" -> "));
                    }
                    Some(Color::Black) => {}
                    None => {
                        color.insert(next.as_str(), Color::Gray);
                        stack.push((next.as_str(), edges[next.as_str()].iter()));
                    }
                },
                None => {
                    color.insert(node, Color::Black);
                    stack.pop();
                }
            }
        }
    }
    Ok(())
}

