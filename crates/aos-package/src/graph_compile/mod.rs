/// What a reconcile changed on disk, returned by
/// [`GraphCompiler::reconcile_filesystem`] so the caller can `reset-failed` the
/// removed instances (build-spec §6).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct ReconcileReport {
    /// Packages whose instances were newly written or rewritten.
    pub written: BTreeSet<String>,
    /// Packages whose stale `/run` units were deleted (removed from the
    /// manifest since the previous compile).
    pub removed: BTreeSet<String>,
}

/// The graph compiler, parameterized by its `/run/systemd/system` root so it can
/// be driven against a tempdir in unit tests.
#[derive(Debug, Clone)]
pub struct GraphCompiler {
    run_root: PathBuf,
}

impl Default for GraphCompiler {
    fn default() -> Self {
        Self::new()
    }
}

impl GraphCompiler {
    /// A compiler writing to the production `/run/systemd/system` root.
    pub fn new() -> Self {
        Self {
            run_root: PathBuf::from(RUN_SYSTEMD_SYSTEM),
        }
    }

    /// A compiler writing under `run_root` (used by tests + `--run-root`).
    pub fn with_run_root(run_root: impl Into<PathBuf>) -> Self {
        Self {
            run_root: run_root.into(),
        }
    }

    /// Render the plan to its on-disk artifact set without touching disk.
    pub fn render(&self, plan: &CompilePlan) -> PlannedArtifacts {
        let mut dropins = BTreeMap::new();
        let mut symlinks = BTreeMap::new();
        for pkg in &plan.packages {
            let deps = plan.edges.get(pkg).cloned().unwrap_or_default();
            // Install dropin (fetch instances get no dropin — they have no edges).
            let dropin = self
                .run_root
                .join(format!("aos-pkg-install@{pkg}.service.d"))
                .join(EDGES_DROPIN);
            dropins.insert(dropin, dropin_contents(pkg, &deps));

            // `.wants/` symlinks: target.wants/<instance> -> ../<template>.
            let fetch_link = self
                .run_root
                .join(format!("{FETCH_TARGET}.wants"))
                .join(format!("aos-pkg-fetch@{pkg}.service"));
            symlinks.insert(fetch_link, PathBuf::from(format!("../{FETCH_TEMPLATE}")));

            let install_link = self
                .run_root
                .join(format!("{RENDER_TARGET}.wants"))
                .join(format!("aos-pkg-install@{pkg}.service"));
            symlinks.insert(install_link, PathBuf::from(format!("../{INSTALL_TEMPLATE}")));
        }
        PlannedArtifacts { dropins, symlinks }
    }

    /// Reconcile `/run/systemd/system` to exactly match `plan` (build-spec §2.5,
    /// §6).
    ///
    /// Writes every desired dropin (dir `0755`, file `0644`) then every desired
    /// `.wants/` symlink (atomic temp+rename), then deletes any stale
    /// `aos-pkg-*@<p>` artifacts for packages no longer in the plan. The result
    /// is a pure function of `plan` (invariant **I3**): re-running is idempotent.
    /// This performs no `daemon-reload` — the caller sequences that and the
    /// `reset-failed` of [`ReconcileReport::removed`].
    ///
    /// # Errors
    ///
    /// Returns an error if any directory, file, or symlink operation fails.
    pub fn reconcile_filesystem(&self, plan: &CompilePlan) -> Result<ReconcileReport> {
        std::fs::create_dir_all(&self.run_root)
            .with_context(|| format!("creating {}", self.run_root.display()))?;

        let artifacts = self.render(plan);

        // (1) dropins.
        for (path, contents) in &artifacts.dropins {
            write_dropin(path, contents)?;
        }
        // (2) symlinks.
        for (path, target) in &artifacts.symlinks {
            write_symlink(path, target)?;
        }
        // (3) prune stragglers (packages removed since the last compile).
        let on_disk = self.scan_existing_packages()?;
        let removed: BTreeSet<String> =
            on_disk.difference(&plan.packages).cloned().collect();
        for pkg in &removed {
            self.remove_package_artifacts(pkg)?;
        }

        Ok(ReconcileReport {
            written: plan.packages.clone(),
            removed,
        })
    }

    /// Full compile: reconcile the filesystem, then drive systemd (build-spec
    /// §2.3–2.4, §6) — `reset-failed` every removed instance, one `daemon-reload`,
    /// then `start --no-block aos-config.target`.
    ///
    /// # Errors
    ///
    /// Returns an error if the filesystem reconcile fails or any systemd call
    /// fails. A failure here exits `aos-graph-compile.service` non-zero and the
    /// box stays on the gen-0 seed (recovery ladder rung 4).
    pub async fn compile<C>(
        &self,
        manifest: &Value,
        graph: &ConfigGraph,
        client: &C,
    ) -> Result<ReconcileReport>
    where
        C: SystemdControl + ?Sized,
    {
        let plan = plan(manifest, graph)?;
        let report = self.reconcile_filesystem(&plan)?;

        // reset-failed each removed instance so a previously-failed unit does
        // not linger (build-spec §6). Both planes (fetch + install) are cleared.
        for pkg in &report.removed {
            client
                .reset_failed_unit(&format!("aos-pkg-fetch@{pkg}.service"))
                .await?;
            client
                .reset_failed_unit(&format!("aos-pkg-install@{pkg}.service"))
                .await?;
        }

        // Exactly one daemon-reload after all files are on disk (build-spec §2.3).
        client.daemon_reload().await?;

        // Start the umbrella target and return immediately; systemd schedules
        // the whole wing asynchronously (build-spec §2.4).
        client.start_unit_no_wait(CONFIG_TARGET).await?;

        Ok(report)
    }

    /// Scan the run root for the packages that currently have `aos-pkg-*@<p>`
    /// instance artifacts (dropin dirs or `.wants` symlinks).
    fn scan_existing_packages(&self) -> Result<BTreeSet<String>> {
        let mut found = BTreeSet::new();

        // Install dropin directories: aos-pkg-install@<p>.service.d
        if let Ok(entries) = std::fs::read_dir(&self.run_root) {
            for entry in entries.flatten() {
                let name = entry.file_name();
                let name = name.to_string_lossy();
                if let Some(pkg) = name
                    .strip_prefix("aos-pkg-install@")
                    .and_then(|rest| rest.strip_suffix(".service.d"))
                    .or_else(|| {
                        name.strip_prefix("aos-pkg-fetch@")
                            .and_then(|rest| rest.strip_suffix(".service.d"))
                    })
                {
                    found.insert(pkg.to_string());
                }
            }
        }

        // `.wants` symlinks under each target.wants directory.
        for (target, prefix) in [
            (FETCH_TARGET, "aos-pkg-fetch@"),
            (RENDER_TARGET, "aos-pkg-install@"),
        ] {
            let dir = self.run_root.join(format!("{target}.wants"));
            if let Ok(entries) = std::fs::read_dir(&dir) {
                for entry in entries.flatten() {
                    let name = entry.file_name();
                    let name = name.to_string_lossy();
                    if let Some(pkg) = name
                        .strip_prefix(prefix)
                        .and_then(|rest| rest.strip_suffix(".service"))
                    {
                        found.insert(pkg.to_string());
                    }
                }
            }
        }

        Ok(found)
    }

    /// Delete every `/run` artifact belonging to `pkg`.
    fn remove_package_artifacts(&self, pkg: &str) -> Result<()> {
        let install_dropin_dir = self
            .run_root
            .join(format!("aos-pkg-install@{pkg}.service.d"));
        remove_dir_if_present(&install_dropin_dir)?;
        // Defensive: a fetch dropin dir is never written, but clean it if a
        // prior version left one.
        let fetch_dropin_dir = self.run_root.join(format!("aos-pkg-fetch@{pkg}.service.d"));
        remove_dir_if_present(&fetch_dropin_dir)?;

        let fetch_link = self
            .run_root
            .join(format!("{FETCH_TARGET}.wants"))
            .join(format!("aos-pkg-fetch@{pkg}.service"));
        remove_file_if_present(&fetch_link)?;
        let install_link = self
            .run_root
            .join(format!("{RENDER_TARGET}.wants"))
            .join(format!("aos-pkg-install@{pkg}.service"));
        remove_file_if_present(&install_link)?;
        Ok(())
    }
}

