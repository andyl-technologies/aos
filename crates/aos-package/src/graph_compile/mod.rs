/// Write a dropin file, creating its `…service.d/` parent (`0755`), with mode
/// `0644`.
fn write_dropin(path: &Path, contents: &str) -> Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .with_context(|| format!("creating {}", parent.display()))?;
        set_mode(parent, 0o755)?;
    }
    // Atomic write (temp + rename) so a crash mid-write never leaves a truncated
    // dropin that a later daemon-reload could load — matching write_symlink.
    let tmp = path.with_extension("conf.tmp");
    std::fs::write(&tmp, contents).with_context(|| format!("writing {}", tmp.display()))?;
    set_mode(&tmp, 0o644)?;
    std::fs::rename(&tmp, path)
        .with_context(|| format!("renaming {} -> {}", tmp.display(), path.display()))?;
    Ok(())
}

/// Create (or atomically replace) a relative symlink `path -> target`.
fn write_symlink(path: &Path, target: &Path) -> Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .with_context(|| format!("creating {}", parent.display()))?;
        set_mode(parent, 0o755)?;
    }
    // If an identical symlink already exists, leave it (idempotent, I3).
    if let Ok(existing) = std::fs::read_link(path)
        && existing == target
    {
        return Ok(());
    }
    // Atomic replace via temp + rename so a wanted unit never momentarily lacks
    // its symlink (build-spec §2.5).
    let tmp = path.with_extension("tmp-aos-graph");
    let _ = std::fs::remove_file(&tmp);
    std::os::unix::fs::symlink(target, &tmp)
        .with_context(|| format!("symlinking {} -> {}", tmp.display(), target.display()))?;
    std::fs::rename(&tmp, path)
        .with_context(|| format!("renaming {} -> {}", tmp.display(), path.display()))?;
    Ok(())
}

/// `chmod` a path, ignoring the operation on platforms without unix perms in a
/// test sandbox (always present on the AOS target).
fn set_mode(path: &Path, mode: u32) -> Result<()> {
    use std::os::unix::fs::PermissionsExt;
    let perms = std::fs::Permissions::from_mode(mode);
    std::fs::set_permissions(path, perms)
        .with_context(|| format!("chmod {mode:o} {}", path.display()))
}

/// Remove a directory tree if it exists, treating absence as success.
fn remove_dir_if_present(path: &Path) -> Result<()> {
    match std::fs::remove_dir_all(path) {
        Ok(()) => Ok(()),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(e) => Err(e).with_context(|| format!("removing {}", path.display())),
    }
}

/// Remove a file/symlink if it exists, treating absence as success.
fn remove_file_if_present(path: &Path) -> Result<()> {
    match std::fs::remove_file(path) {
        Ok(()) => Ok(()),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(e) => Err(e).with_context(|| format!("removing {}", path.display())),
    }
}

